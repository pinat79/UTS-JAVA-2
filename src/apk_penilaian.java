    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
       
String nim = txtNIM.getText();
String nama = txtNAMA.getText();
String matkul = cmbMataKuliah.getSelectedItem().toString();
String sks = txtSKS.getText();
String nilaiAkhir = txtNILAI_AKHIR.getText();
String grade = txtGRADE.getText();

if (nim.isEmpty() || nama.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "NIM dan Nama harus diisi!"
    );
    return;
}

if (nilaiAkhir.isEmpty() || grade.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Klik PROSES terlebih dahulu!"
    );
    return;
}

txtOutput.append(
    "NIM: " + nim + "\n" +
    "Nama: " + nama + "\n" +
    "Mata Kuliah: " + matkul + "\n" +
    "SKS: " + sks + "\n" +
    "Nilai Akhir: " + nilaiAkhir + "\n" +
    "Grade: " + grade + "\n" +
    "--------------------------\n"
);
 
    }//GEN-LAST:event_btnAddActionPerformed

